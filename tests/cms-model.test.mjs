import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {safeURL,escapeHTML,localAsset,publicItems,validateItem,validateProfile} from '../cms/model.mjs';
assert.equal(safeURL('javascript:alert(1)'), '');
assert.equal(safeURL('data:image/svg+xml,<svg onload=alert(1)>',{image:true}), '');
assert.equal(safeURL('//evil.example/x'), '');
assert.equal(safeURL('https://u:secret@example.com'), '');
assert.equal(safeURL('image/../../secret'), '');
assert.equal(safeURL('https://example.com/" onerror="bad'), 'https://example.com/%22%20onerror=%22bad');
assert.equal(localAsset('image/project.png','../'),'../image/project.png');
assert.equal(escapeHTML('<img src=x onerror="bad">'), '&lt;img src=x onerror=&quot;bad&quot;&gt;');
assert.deepEqual(publicItems([{title:'draft',published:false},{title:'public',published:true,sort_order:0}]).map(r=>r.title),['public']);
assert.throws(()=>validateItem({kind:'photo',title:'Photo',image_url:''}),/image/);
assert.throws(()=>validateItem({kind:'project',title:'X',current_focus:true,work_status:'completed'}),/In progress/);
assert.throws(()=>validateItem({kind:'project',title:'X',live_url:'javascript:evil()'}),/URL/);
assert.throws(()=>validateItem({kind:'project',title:'X',sort_order:0.5}),/whole/);
assert.throws(()=>validateProfile({name:'X',email:'invalid'}),/email/);
const seed=JSON.parse(await readFile(new URL('../data/portfolio.json',import.meta.url)));
for(const row of seed.items)validateItem(row);
validateProfile(seed.profile.data);
assert.equal(seed.items.length,69);
assert.equal(new Set(seed.items.map(r=>r.id)).size,69);
assert.equal(seed.items.filter(r=>r.kind==='photo').length,46);
console.log('PASS: URL safety, escaped content, publication filters, record/profile validation, all 69 migrated records.');
